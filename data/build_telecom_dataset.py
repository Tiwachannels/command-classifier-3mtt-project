"""
Builds the telecom-specific training dataset by combining:
  1. The synthetic Nigerian Pidgin/English telecom dataset (22 intents,
     generated by generate_data.py) - this is what gives the model its
     local-context uniqueness.
  2. Real English examples from the CLINC-style dataset, but ONLY for
     intents where the phrasing genuinely generalizes to a telecom IVR
     context (greetings, yes/no, fraud reporting, calling, etc.) - NOT
     forced/relabeled from bank-specific phrasing that wouldn't actually
     transfer (e.g. we do NOT reuse "direct_deposit" text for anything).

Label mapping from the real dataset's intent names to our telecom intent
names, where they differ:
  balance      -> check_balance
  make_call    -> call_contact
(report_fraud, greeting, goodbye, thank_you, yes, no, cancel, repeat,
 are_you_a_bot keep the same name in both datasets)
"""
import pandas as pd

SYNTHETIC_PATH = "/home/claude/voice_command_classifier/data/intents_dataset.csv"
FULL_150_PATH = "/home/claude/voice_command_classifier/data/full_150_intents_en.csv"
OUTPUT_PATH = "/home/claude/voice_command_classifier/data/telecom_dataset.csv"

# Intents to pull from the real dataset, mapped to our telecom intent names.
# Only includes intents whose real-world phrasing is domain-general enough
# to genuinely apply to a telecom IVR context.
REAL_INTENT_MAP = {
    "balance": "check_balance",
    "report_fraud": "report_fraud",
    "make_call": "call_contact",
    "greeting": "greeting",
    "goodbye": "goodbye",
    "thank_you": "thank_you",
    "yes": "yes",
    "no": "no",
    "cancel": "cancel",
    "repeat": "repeat",
    "are_you_a_bot": "are_you_a_bot",
}


def main():
    synthetic_df = pd.read_csv(SYNTHETIC_PATH)
    full_df = pd.read_csv(FULL_150_PATH)

    real_rows = []
    for real_intent, telecom_intent in REAL_INTENT_MAP.items():
        subset = full_df[full_df["intent"] == real_intent].copy()
        subset["intent"] = telecom_intent
        real_rows.append(subset)

    real_combined = pd.concat(real_rows, ignore_index=True)

    combined = pd.concat([synthetic_df, real_combined], ignore_index=True)
    combined = combined.drop_duplicates().reset_index(drop=True)

    combined.to_csv(OUTPUT_PATH, index=False)

    print(f"Synthetic (Pidgin/telecom-specific): {len(synthetic_df)} examples")
    print(f"Real (from CLINC dataset, overlapping intents): {len(real_combined)} examples")
    print(f"Combined total: {len(combined)} examples across {combined['intent'].nunique()} intents")
    print("\nExamples per intent:")
    print(combined["intent"].value_counts().sort_index())


if __name__ == "__main__":
    main()
